  const supported = ['ru', 'en']
  let locale = supported.includes(localStorage.getItem('proxyfleet.locale')) ? localStorage.getItem('proxyfleet.locale') : 'ru'

  function t(source, variables = {}) {
    let result = catalogs[locale]?.[source] || source
    Object.entries(variables).forEach(([key, value]) => { result = result.replaceAll(`{${key}}`, String(value)) })
    return result
  }

  function translateTextNode(node) {
    const current = node.nodeValue
    if (!current.trim()) return
    if (node.__i18nRendered !== current) node.__i18nSource = current
    const source = node.__i18nSource || current
    const trimmed = source.trim()
    const translated = t(trimmed)
    const rendered = source.replace(trimmed, translated)
    node.nodeValue = rendered
    node.__i18nRendered = rendered
  }

  function translateAttribute(element, name) {
    const current = element.getAttribute(name)
    if (!current) return
    const key = `i18n${name.replace(/(^|-)(\w)/g, (_, __, char) => char.toUpperCase())}Source`
    const renderedKey = `${key}Rendered`
    if (element.dataset[renderedKey] !== current) element.dataset[key] = current
    const source = element.dataset[key] || current
    const rendered = t(source)
    element.setAttribute(name, rendered)
    element.dataset[renderedKey] = rendered
  }

  function apply(root = document) {
    document.documentElement.lang = locale
    document.documentElement.dir = 'ltr'
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
    const nodes = []
    while (walker.nextNode()) nodes.push(walker.currentNode)
    nodes.forEach(node => {
      const parent = node.parentElement
      if (!parent || ['SCRIPT', 'STYLE', 'CODE'].includes(parent.tagName)) return
      translateTextNode(node)
    })
    root.querySelectorAll?.('[placeholder], [aria-label], [title], [alt]').forEach(element => {
      ;['placeholder', 'aria-label', 'title', 'alt'].forEach(name => {
        if (element.hasAttribute(name)) translateAttribute(element, name)
      })
    })
  }

  function setLocale(next) {
    if (!supported.includes(next) || next === locale) return
    locale = next
    localStorage.setItem('proxyfleet.locale', locale)
    apply()
    document.dispatchEvent(new CustomEvent('proxyfleet:localechange', { detail: { locale } }))
  }

  function localeTag() { return locale === 'en' ? 'en-GB' : 'ru-RU' }

  window.I18n = { apply, locale: () => locale, localeTag, setLocale, t }
